"""Realistic fixture validation tests for Phase 2.5 Common Evidence Model.

Executes the complete evidence extraction and aggregation pipeline on:
1. tests/fixtures/fastapi_project
2. tests/fixtures/node_ts_project
and verifies determinism, concept coverage, and absence synthesis.
"""

from __future__ import annotations

from pathlib import Path

from sdat.evidence.aggregator import EvidenceAggregator
from sdat.models import EvidenceKind
from sdat.scanners.python import PythonScanner
from sdat.scanners.typescript import TypeScriptScanner


class TestFixtureValidation:
    """Validate full pipeline execution on realistic project fixtures."""

    def test_fastapi_project_pipeline(self):
        root = Path("tests/fixtures/fastapi_project")
        assert root.exists()

        scanner = PythonScanner()
        aggregator = EvidenceAggregator(target_root=root)

        # 1. Scan project evidence -> FileEvidence list
        file_evidences = scanner.scan_project_evidence(root)
        assert len(file_evidences) >= 5

        total_facts = []
        for fe in file_evidences:
            total_facts.extend(fe.facts)

        assert len(total_facts) > 20
        unique_facts = aggregator.correlate(total_facts)
        assert len(unique_facts) <= len(total_facts)

        # 2. Bundles generated by concept
        bundles = aggregator.aggregate(total_facts)
        assert len(bundles) >= 5

        concept_ids = {b.concept_id for b in bundles}
        # Check core foundation concepts are covered
        expected = {
            "foundation.config",
            "foundation.caching",
            "foundation.logging",
            "data.orm",
            "api.rest",
        }
        assert expected.issubset(concept_ids) or any(c in concept_ids for c in expected)

        # 3. Absence synthesis verification
        absence_facts = aggregator.synthesize_absence(unique_facts)
        # Verify absence facts are cleanly typed
        for af in absence_facts:
            assert af.kind == EvidenceKind.ABSENT_PATTERN

        # 4. Determinism check (Run twice, verify identical output)
        file_evidences_2 = scanner.scan_project_evidence(root)
        total_facts_2 = [f for fe in file_evidences_2 for f in fe.facts]
        bundles_2 = aggregator.aggregate(total_facts_2)

        assert [b.concept_id for b in bundles] == [b.concept_id for b in bundles_2]
        assert [len(b.facts) for b in bundles] == [len(b.facts) for b in bundles_2]

    def test_node_ts_project_pipeline(self):
        root = Path("tests/fixtures/node_ts_project")
        assert root.exists()

        scanner = TypeScriptScanner()
        aggregator = EvidenceAggregator(target_root=root)

        file_evidences = scanner.scan_project_evidence(root)
        assert len(file_evidences) >= 5

        total_facts = [f for fe in file_evidences for f in fe.facts]
        assert len(total_facts) > 15

        unique_facts = aggregator.correlate(total_facts)
        assert len(unique_facts) > 0
        bundles = aggregator.aggregate(total_facts)
        assert len(bundles) >= 4

        concept_ids = {b.concept_id for b in bundles}
        assert any(c in concept_ids for c in ("foundation.config", "foundation.caching", "foundation.logging", "api.rest"))

        # Determinism check
        bundles_2 = aggregator.aggregate(total_facts)
        assert [b.concept_id for b in bundles] == [b.concept_id for b in bundles_2]
